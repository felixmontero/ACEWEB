function createAceIcons(attrs = {}) {
  const defaults = {
    xmlns: "http://www.w3.org/2000/svg",
    width: "24",
    height: "24",
    viewBox: "0 0 24 24",
    fill: "none",
    stroke: "currentColor",
    "stroke-width": "2",
    "stroke-linecap": "round",
    "stroke-linejoin": "round",
    class: "lucide"
  };

  document.querySelectorAll("[data-lucide]").forEach((placeholder) => {
    const name = placeholder.getAttribute("data-lucide");
    const nodes = ACE_ICON_NODES[name];
    if (!nodes) return;

    const svg = document.createElementNS("http://www.w3.org/2000/svg", "svg");
    const merged = { ...defaults, ...attrs };
    Object.entries(merged).forEach(([key, value]) => svg.setAttribute(key, value));
    svg.classList.add(`lucide-${name}`);

    [...placeholder.attributes].forEach((attribute) => {
      if (attribute.name === "data-lucide") return;
      svg.setAttribute(attribute.name, attribute.value);
    });

    nodes.forEach(([tag, nodeAttrs]) => {
      const child = document.createElementNS("http://www.w3.org/2000/svg", tag);
      Object.entries(nodeAttrs).forEach(([key, value]) => child.setAttribute(key, value));
      svg.appendChild(child);
    });

    placeholder.replaceWith(svg);
  });
}
